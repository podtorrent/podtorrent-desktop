#!/usr/bin/env bash
# Build a headless tarball: uv, the Python backend, podtorrent-agent, the `podtorrent` launcher and
# README.md (the user's guide). No Tauri, no GTK. uv and the agent are copied in, so run it on the target's
# OS and CPU.
#
#   PODTORRENT_AGENT_BIN=/path/to/podtorrent-agent headless/package.sh [out-dir]
#
# PODTORRENT_PLATFORM picks the build:
#   rocm (default)  podtorrent-X.Y.Z-linux-x64-rocm-headless.tar.gz, on Linux x86_64: the backend locked to
#                   ROCm PyTorch from PODTORRENT_TORCH_INDEX (default gfx1151, Strix Halo).
#   jetson          podtorrent-X.Y.Z-linux-arm64-jetson-headless.tar.gz, on Linux aarch64: the backend locked
#                   to CPU PyTorch, plus jetson-torch.txt, from which the launcher installs NVIDIA's Jetson
#                   PyTorch for the machine's JetPack on first run. JETSON_TORCH_INDEX_JP<N> (with
#                   JETSON_TORCH_REQ_JP<N>, default "torch") adds JetPack N; JetPack 6 and 7 have defaults.
#   macos           podtorrent-X.Y.Z-macos-arm64-headless.tar.gz, on an Apple Silicon Mac: the backend as the Mac
#                   app has it (MLX from the lock, no PyTorch), run by launchd instead of a window.
# VERSION overrides the version in the file name (default: pyproject.toml's).
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$(mkdir -p "${1:-$root/dist}" && cd "${1:-$root/dist}" && pwd)"
version="${VERSION:-$(sed -n 's/^version = "\(.*\)"/\1/p' "$root/pyproject.toml" | head -n1)}"
platform="${PODTORRENT_PLATFORM:-rocm}"
case "$platform" in
  rocm) build=linux-x64-rocm-headless; arch=x86_64
        torch_index="${PODTORRENT_TORCH_INDEX:-https://repo.amd.com/rocm/whl/gfx1151/}"; lock_check='repo.amd.com/rocm' ;;
  jetson) build=linux-arm64-jetson-headless; arch=aarch64
        torch_index=https://download.pytorch.org/whl/cpu; lock_check='download.pytorch.org/whl/cpu' ;;
  macos) build=macos-arm64-headless; arch=arm64; torch_index=""; lock_check='' ;;
  *) echo "unknown PODTORRENT_PLATFORM $platform (rocm, jetson, macos)" >&2; exit 1 ;;
esac
[[ "$(uname -m)" == "$arch" ]] || { echo "build $build on $arch (this is $(uname -m)): uv is copied in" >&2; exit 1; }
name="podtorrent-$version-$build"   # the naming standard: downloads/src/builds.json
stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT

mkdir -p "$stage/$name"
PODTORRENT_BACKEND_OUT="$stage/$name/backend" \
PODTORRENT_TORCH_INDEX="$torch_index" \
  node "$root/app/scripts/bundle-backend.js"
[[ -x "$stage/$name/backend/podtorrent-agent" ]] || { echo "podtorrent-agent was not staged; set PODTORRENT_AGENT_BIN" >&2; exit 1; }
[[ -z "$lock_check" ]] || grep -q "$lock_check" "$stage/$name/backend/pyproject.toml" || { echo "backend is not locked to $lock_check" >&2; exit 1; }
if [[ "$platform" == jetson ]]; then
  # JetPack major -> NVIDIA's Jetson PyTorch index and the requirement to install from it. JetPack 6 (L4T R36,
  # CUDA 12.x): jp6/cu129 is the index with Python 3.12 wheels (cu126 has 3.10 only, which the backend can't use).
  : "${JETSON_TORCH_INDEX_JP6:=https://pypi.jetson-ai-lab.io/jp6/cu129/+simple}" "${JETSON_TORCH_REQ_JP6:=torch==2.8.0}"
  # JetPack 7 (L4T R38 Thor, R39 Orin) moved Jetson to the standard ("SBSA") aarch64 CUDA 13, so PyTorch's
  # own cu130 aarch64 wheel fits, with CUDA from its nvidia-* pip dependencies. Its GPU code includes sm_80,
  # which runs on Orin (sm_87). Not Jetson AI Lab's sbsa/cu130: that torch has sm_100/110/121 only (Thor,
  # GB10), no sm_8x and no PTX, so it can't run on Orin. The wheel links NVIDIA's ARM BLAS/LAPACK (NVPL)
  # without declaring it, so the requirement adds nvpl-blas and nvpl-lapack (installed --no-deps).
  : "${JETSON_TORCH_INDEX_JP7:=https://download.pytorch.org/whl/cu130}"
  : "${JETSON_TORCH_REQ_JP7:=torch==2.10.0 nvpl-blas==0.6.1 nvpl-lapack==0.4.1}"
  {
    echo "# JetPack  PyTorch index  requirement  [extra libraries from PyPI, --no-deps]   (read by the podtorrent launcher; generated by headless/package.sh)"
    for jp in 5 6 7 8; do
      idx="JETSON_TORCH_INDEX_JP$jp"; req="JETSON_TORCH_REQ_JP$jp"
      [[ -z "${!idx:-}" ]] || echo "$jp ${!idx} ${!req:-torch}"
    done
  } >"$stage/$name/jetson-torch.txt"
  cat "$stage/$name/jetson-torch.txt"
fi
printf '%s\n' "$platform" >"$stage/$name/PLATFORM"
cp "$root/headless/podtorrent" "$stage/$name/podtorrent"
cp "$root/headless/README.md" "$stage/$name/README.md"
printf '%s\n' "$version" >"$stage/$name/VERSION"
chmod +x "$stage/$name/podtorrent"
COPYFILE_DISABLE=1 tar -C "$stage" -czf "$out/$name.tar.gz" "$name"
echo "$out/$name.tar.gz"
